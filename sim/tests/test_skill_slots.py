def test_the_damage_target_is_what_a_basic_attack_does():
    """Which is what makes settling this cost nothing. The tier 8 target and
    every affix value were fitted to an ordinary hit."""
    assert af.damage_for_slot("Basic") == pytest.approx(af.damage_target(8))


def test_the_other_slots_multiply_from_that_target():
    target = af.damage_target(8)
    for slot, expected in (("Heavy", 2.5), ("Special", 1.5), ("Ultimate", 4.0),
                           ("Movement", 1.0), ("Aura", 0.25)):
        assert af.damage_for_slot(slot) == pytest.approx(target * expected)


def test_an_unknown_slot_is_rejected_when_asked_what_it_deals():
    with pytest.raises(ValueError, match="unknown skill slot"):
        af.damage_for_slot("Passive")


def test_settling_this_left_the_weapon_figure_meaning_the_weapon():
    """It used to be the weapon and the skill together, because no skill had a
    multiplier. With the basic attack at 100%, it is the weapon alone."""
    target = af.damage_target(8)
    weapon = af.weapon_base_damage_needed(target, 6, 6)
    assert weapon > 0
    from_affixes = af.FLAT_DAMAGE.value_at(7) * 6
    assert weapon + from_affixes == pytest.approx(
        target / (1 + af.INCREASED_DAMAGE.value_at(7) / 100.0 * 6))


def test_an_ultimate_is_worth_several_common_enemies():
    """A sanity check that the top of the scale means something. At tier 8 an
    Ultimate should clear a pack rather than dent one enemy."""
    from cataclysm_sim import enemy_stats as es
    common = es.stats_on_floor("Common", 8, "Cataclysm")
    assert af.damage_for_slot("Ultimate") > 1.5 * common.effective_health


