def test_the_slots_match_the_design_documents_table():
    """`Cataclysm_GDD_v2.md` lists seven rows in its Skill Slots table."""
    assert set(ch.SKILL_SLOTS) == {"Basic", "Heavy", "Special", "Support",
                                   "Aura", "Ultimate", "Movement"}


def test_a_player_chooses_six_of_them():
    """The design says six slots and that the basic attack is automatic, so the
    seventh is not one a player spends."""
    assert len(ch.CHOSEN_SKILL_SLOTS) == 6
    assert ch.BASIC_ATTACK_SLOT not in ch.CHOSEN_SKILL_SLOTS


def test_that_slot_list_check_actually_fires():
    real = dict(ch.SKILL_SLOTS)
    ch.SKILL_SLOTS.pop("Aura")
    try:
        with pytest.raises(ValueError, match="drifted from the design"):
            ch._check_the_slots_match_the_design_document()
    finally:
        ch.SKILL_SLOTS.clear()
        ch.SKILL_SLOTS.update(real)


def test_the_basic_attack_is_exactly_one_hundred_percent():
    """It is the anchor. Every damage figure already fitted -- the tier 8 target,
    the affix values, what a weapon must supply -- was fitted to an ordinary hit,
    and an ordinary hit is the basic attack. If this stopped being 100%, all of
    them would silently mean something else."""
    basic = ch.SKILL_SLOTS[ch.BASIC_ATTACK_SLOT]
    assert basic.typical_damage == basic.lowest == basic.highest == 100.0


def test_that_anchor_check_actually_fires():
    real = ch.SKILL_SLOTS[ch.BASIC_ATTACK_SLOT]
    ch.SKILL_SLOTS[ch.BASIC_ATTACK_SLOT] = ch.SkillSlot(
        "Basic", 120.0, 120.0, 120.0, "moved")
    try:
        with pytest.raises(ValueError, match="must be exactly 100%"):
            ch._check_the_basic_attack_is_the_anchor()
    finally:
        ch.SKILL_SLOTS[ch.BASIC_ATTACK_SLOT] = real


@pytest.mark.parametrize("slot", sorted(ch.SKILL_SLOTS))
def test_every_slots_typical_value_sits_inside_its_own_band(slot):
    s = ch.SKILL_SLOTS[slot]
    assert s.lowest <= s.typical_damage <= s.highest


def test_a_band_that_does_not_contain_its_typical_value_is_rejected():
    with pytest.raises(ValueError, match="outside its"):
        ch.SkillSlot("Bad", 500.0, 100.0, 200.0, "impossible")


def test_the_ultimate_is_the_biggest_hit_and_support_the_smallest():
    """A skill on a long cooldown should be worth more per use than one that is
    off cooldown constantly, and a buff should not be a damage skill."""
    typical = {n: s.typical_damage for n, s in ch.SKILL_SLOTS.items()}
    assert typical["Ultimate"] == max(typical.values())
    assert typical["Support"] == min(typical.values())
    assert typical["Heavy"] > typical["Special"] > typical["Basic"]


# --------------------------------------------------------------------------
# The numbers came out of the designed skills, not out of nowhere
# --------------------------------------------------------------------------

def stated_multipliers(damage_type: str | None = None) -> dict[str, float]:
    """Every skill in the data whose description states a weapon multiplier.

    THIS READS THE GAME DATA, which the simulation package itself never does and
    should not start doing. It is here because these three tests exist to prove
    the slot values were derived from the designed skills rather than invented,
    and that claim cannot be checked against anything else.

    Pass a damage type to restrict the answer to it. The War set is the evidence
    the slot bands were read off, so the test below pins that set exactly; every
    damage type designed afterwards is checked against the bands instead, which
    is the direction the evidence actually runs.
    """
    if not WEAPON_SKILLS.exists():
        raise AssertionError(
            f"{WEAPON_SKILLS} is missing, so the claim that the skill slot "
            "values came from the designed skills cannot be checked. It is "
            "generated by tools/generate_datatables.py.")
    found = {}
    with WEAPON_SKILLS.open(encoding="utf-8-sig") as handle:
        for row in csv.DictReader(handle):
            if damage_type is not None and row["DamageType"] != damage_type:
                continue
            match = re.search(r"(\d+)%\s+weapon damage",
                              row["SkillDescription"] or "", re.I)
            if match:
                found[row["SkillName"]] = float(match.group(1))
    return found


def test_the_designed_skills_already_state_weapon_damage_multipliers():
    """This is why the concept was not invented here. Four of the 61 designed
    War skills in `game/Data/WeaponSkills.csv` say what they are worth in prose.

    Pinned to War on purpose. War was the only complete damage type when the
    slot bands were derived, so it is the evidence for them. A later damage type
    stating its own figure is not evidence and must not silently widen a band;
    it is checked against the bands by the two tests below instead.
    """
    stated = stated_multipliers("War")
    assert stated == {"Haymaker": 100.0, "Bulwark": 200.0,
                      "Annihilator": 300.0, "Skull Splitter": 500.0}


def test_the_ultimate_band_is_the_two_designed_ultimates():
    """Derived rather than picked. Annihilator states 300% and Skull Splitter
    states 500%, so the band is exactly those two."""
    ultimate = ch.SKILL_SLOTS["Ultimate"]
    stated = stated_multipliers()
    assert ultimate.lowest == stated["Annihilator"] == 300.0
    assert ultimate.highest == stated["Skull Splitter"] == 500.0


def test_every_designed_multiplier_fits_inside_some_slots_band():
    """A stated figure outside every band would mean the bands are wrong."""
    bands = [(s.lowest, s.highest) for s in ch.SKILL_SLOTS.values()]
    for name, value in stated_multipliers().items():
        assert any(low <= value <= high for low, high in bands), (
            f"{name} states {value}% and no slot's band contains it")


